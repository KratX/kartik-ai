import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { describe, it } from 'node:test';
import { InMemoryObjectStorage } from '@kartik/shared/storage';
import {
  AGENT_RATE_LIMITS_PER_MINUTE,
  AgentGraphExecutor,
  AgentSlidingWindowRateLimiter,
  buildPdfBinaryBuffer,
  classifyCodingIntent,
  DailyLiveBudgetGuard,
  extractTextPagesFromPdfBytes,
  FileIngestionAndArtifactService,
  InMemoryAgentRateLimitStore,
  InMemoryAgentRepository,
  InMemoryDailyBudgetStore,
  InMemoryVectorStore,
  LiveGeminiChatModelProvider,
  LiveGeminiCodingModelProvider,
  LiveGeminiEmbeddingProvider,
  LiveGeminiImageGenerationProvider,
  LiveGeminiPdfDocumentProvider,
  LiveGeminiPptPresentationProvider,
  LiveGeminiSearchProvider,
  LiveGeminiVisionProvider,
  loadAgentConfig,
  MOCK_PNG_BYTES,
} from '../src/index.js';

const { publicKey } = crypto.generateKeyPairSync('ed25519');
const TEST_PUBLIC_PEM = publicKey.export({ type: 'spki', format: 'pem' }).toString();

function createTestConfig() {
  return loadAgentConfig({
    NODE_ENV: 'test',
    DATABASE_URL: 'postgresql://kartik:kartik@127.0.0.1:5432/kartik',
    REDIS_URL: 'redis://127.0.0.1:6379',
    USER_CONTEXT_PUBLIC_KEY: TEST_PUBLIC_PEM,
    INTERNAL_CALLER_TOKEN_CHAT: 'internal-secret-token-chat-to-agent',
    MOCK_AI: 'true',
    GEMINI_API_KEY: 'test-gemini-api-key-value',
    TAVILY_API_KEY: 'test-tavily-api-key',
    DAILY_LIVE_CALL_BUDGET: '25',
  });
}

describe('Phase 9.2.a — Live Gemini Providers, Real PDF Binary Loader, Coding Intent Classifier & Per-Agent Rate Limiter', () => {
  it('enforces per-agent sliding-window rate limits (chat: 20/min, specialists: 5/min) and rejects excess calls with 429 RATE_LIMITED', async () => {
    assert.equal(AGENT_RATE_LIMITS_PER_MINUTE.chat, 20);
    assert.equal(AGENT_RATE_LIMITS_PER_MINUTE.coding, 5);
    assert.equal(AGENT_RATE_LIMITS_PER_MINUTE.pdf, 5);
    assert.equal(AGENT_RATE_LIMITS_PER_MINUTE.ppt, 5);
    assert.equal(AGENT_RATE_LIMITS_PER_MINUTE.rag, 5);
    assert.equal(AGENT_RATE_LIMITS_PER_MINUTE.vision, 5);
    assert.equal(AGENT_RATE_LIMITS_PER_MINUTE.image, 5);
    assert.equal(AGENT_RATE_LIMITS_PER_MINUTE.search, 5);

    let nowMs = 1_700_000_000_000;
    const limiter = new AgentSlidingWindowRateLimiter({
      store: new InMemoryAgentRateLimitStore(() => nowMs),
      windowSeconds: 60,
    });

    for (let i = 1; i <= 5; i++) {
      const decision = await limiter.checkAgentLimit({
        userId: 'usr_rate_test',
        agent: 'pdf',
        nowMs,
      });
      assert.equal(decision.allowed, true);
      assert.equal(decision.currentCount, i);
      assert.equal(decision.limitPerMinute, 5);
    }

    await assert.rejects(
      async () => {
        await limiter.checkAgentLimit({
          userId: 'usr_rate_test',
          agent: 'pdf',
          nowMs,
        });
      },
      (err: { code?: string; httpStatus?: number }) => {
        assert.equal(err.code, 'RATE_LIMITED');
        assert.equal(err.httpStatus, 429);
        return true;
      },
    );

    // Advancing past the 60-second window resets the counter
    nowMs += 61_000;
    const afterReset = await limiter.checkAgentLimit({
      userId: 'usr_rate_test',
      agent: 'pdf',
      nowMs,
    });
    assert.equal(afterReset.allowed, true);
    assert.equal(afterReset.currentCount, 1);
  });

  it('extracts multi-page text from real %PDF-1.4 binary bytes and indexes chunks automatically via FileIngestionAndArtifactService', async () => {
    const compiledPdf = buildPdfBinaryBuffer({
      title: 'Distributed Consensus Architecture',
      subtitle: 'Raft and Paxos Quorum Invariants',
      sections: [
        {
          heading: 'Leader Election Protocol',
          content:
            'Randomized election timeouts prevent split-vote livelocks across distributed consensus nodes.',
          bullets: [
            'Monotonic term numbers identify stale leaders immediately',
            'Quorum intersection guarantees at most one leader per term',
          ],
        },
        {
          heading: 'Log Replication Safety',
          content:
            'Committed log entries are durable across a majority of follower state machines before client acknowledgment.',
          bullets: ['AppendEntries RPC enforces log matching invariant'],
        },
      ],
      footer: 'Generated by Kartik.ai',
    });

    const extractedPages = extractTextPagesFromPdfBytes(compiledPdf.pdfBytes);
    assert.ok(extractedPages.length >= 1);
    assert.equal(extractedPages[0]?.pageNumber, 1);
    assert.ok(extractedPages[0]?.text.includes('Distributed Consensus Architecture'));
    assert.ok(extractedPages[0]?.text.includes('Leader Election Protocol'));

    const config = createTestConfig();
    const repository = new InMemoryAgentRepository();
    const objectStorage = new InMemoryObjectStorage();
    const vectorStore = new InMemoryVectorStore();
    const embeddingProvider = new LiveGeminiEmbeddingProvider();

    const ingestionService = new FileIngestionAndArtifactService({
      config,
      repository,
      objectStorage,
      vectorStore,
      embeddingProvider,
    });

    // Omit `extractedPdfPages` so `ingestUploadedFile` parses the real `%PDF-1.4` binary bytes directly!
    const uploaded = await ingestionService.ingestUploadedFile({
      userId: 'usr_pdf_rag',
      conversationId: 'conv_pdf_rag',
      originalFilename: 'consensus-paper.pdf',
      declaredMimeType: 'application/pdf',
      contentBytes: compiledPdf.pdfBytes,
    });

    assert.equal(uploaded.status, 'ready');
    assert.ok((uploaded.pageCount ?? 0) >= 1);
    assert.ok(uploaded.chunkCount >= 1);

    const [queryVec] = await embeddingProvider.embedTexts(['Leader Election Protocol']);
    const searchHits = await vectorStore.searchChunks({
      userId: 'usr_pdf_rag',
      queryVector: queryVec ?? [],
      fileIds: [uploaded.fileId],
      topK: 3,
    });
    assert.ok(searchHits.length >= 1);
    assert.ok(searchHits[0]?.textContent.includes('Leader Election Protocol'));
  });

  it('classifies Coding Agent intents into 5 categories and distinguishes CODE_GENERATION artifacts from inline CODE_REVIEW / DEBUGGING Markdown', async () => {
    assert.equal(
      classifyCodingIntent('Build an interactive calculator app in HTML CSS JS'),
      'CODE_GENERATION',
    );
    assert.equal(
      classifyCodingIntent('Please review and critique this authentication middleware for code quality'),
      'CODE_REVIEW',
    );
    assert.equal(
      classifyCodingIntent('Debug this TypeError: Cannot read properties of undefined'),
      'DEBUGGING',
    );
    assert.equal(
      classifyCodingIntent('Optimize this nested loop to reduce time complexity'),
      'OPTIMIZATION',
    );
    assert.equal(
      classifyCodingIntent('Explain how closures work in TypeScript'),
      'CODE_EXPLANATION',
    );

    const config = createTestConfig();
    const repository = new InMemoryAgentRepository();
    const objectStorage = new InMemoryObjectStorage();
    const vectorStore = new InMemoryVectorStore();
    const budgetGuard = new DailyLiveBudgetGuard({
      store: new InMemoryDailyBudgetStore(),
      dailyLimit: 25,
      mockAiDefault: false,
    });

    const executor = new AgentGraphExecutor({
      config,
      budgetGuard,
      chatProvider: new LiveGeminiChatModelProvider(),
      codingProvider: new LiveGeminiCodingModelProvider(),
      searchProvider: new LiveGeminiSearchProvider(),
      embeddingProvider: new LiveGeminiEmbeddingProvider(),
      imageProvider: new LiveGeminiImageGenerationProvider(),
      visionProvider: new LiveGeminiVisionProvider(),
      pdfProvider: new LiveGeminiPdfDocumentProvider(),
      pptProvider: new LiveGeminiPptPresentationProvider(),
      vectorStore,
      objectStorage,
      metadataStore: repository,
    });

    // 1. CODE_REVIEW -> returns inline Markdown without creating an artifact
    const reviewRes = await executor.execute({
      requestId: 'req_coding_review_0001',
      traceId: 'trc_coding_review_0001',
      userId: 'usr_coder_1',
      conversationId: 'conv_coder_1',
      messageId: 'msg_coding_review_0001',
      prompt: 'Please review and audit this SQL transaction code for best practices',
      preferredAgent: 'coding',
    });
    assert.equal(reviewRes.agent, 'coding');
    assert.equal(reviewRes.artifactIds, undefined);
    assert.ok(reviewRes.replyContent.includes('CODE_REVIEW'));

    // 2. CODE_GENERATION -> creates a multi-file code_bundle artifact (`index.html`, `styles.css`, `app.js`)
    const genRes = await executor.execute({
      requestId: 'req_coding_gen_0002',
      traceId: 'trc_coding_gen_0002',
      userId: 'usr_coder_1',
      conversationId: 'conv_coder_1',
      messageId: 'msg_coding_gen_0002',
      prompt: 'Build a Netflix movie discovery UI clone',
      preferredAgent: 'coding',
    });
    assert.equal(genRes.agent, 'coding');
    assert.equal(genRes.artifactIds?.length, 1);
    const artifact = await repository.getArtifactById('usr_coder_1', genRes.artifactIds![0]!);
    assert.ok(artifact);
    assert.equal(artifact.artifactType, 'code_bundle');
    assert.equal(artifact.filesManifest.length, 3);
  });

  it('executes LiveGeminiSearchProvider (with topic image gallery), Vision, PDF, PPT, and Image providers with structured outputs', async () => {
    const searchProvider = new LiveGeminiSearchProvider();
    const results = await searchProvider.searchWeb({
      query: 'PostgreSQL MVCC concurrency control',
      maxResults: 3,
    });
    assert.ok(results.length >= 1);
    assert.equal(searchProvider.lastSearchImages.length, 4);
    assert.ok(searchProvider.lastSearchImages[0]?.imageUrl.startsWith('data:image/svg+xml;utf8,'));

    const visionProvider = new LiveGeminiVisionProvider();
    const visionOut = await visionProvider.analyzeImage({
      prompt: 'Extract text and layout structure from this diagram',
      mimeType: 'image/png',
      imageBytes: MOCK_PNG_BYTES,
    });
    assert.ok(visionOut.analysis.includes('image/png'));

    const pdfProvider = new LiveGeminiPdfDocumentProvider();
    const pdfOut = await pdfProvider.generatePdfDocument({
      prompt: 'Create a PDF technical report on Zero-Trust Service Mesh',
      maxOutputTokens: 2048,
    });
    assert.equal(Buffer.from(pdfOut.pdfBytes.subarray(0, 8)).toString('ascii'), '%PDF-1.4');

    const pptProvider = new LiveGeminiPptPresentationProvider();
    const pptOut = await pptProvider.generatePptPresentation({
      prompt: 'Create a 6-slide presentation on Cloud Native Observability',
      maxOutputTokens: 2048,
    });
    assert.equal(pptOut.pptxBytes[0], 0x50);
    assert.equal(pptOut.pptxBytes[1], 0x4b);
    assert.equal(pptOut.slideCount, 8);

    const imageProvider = new LiveGeminiImageGenerationProvider();
    const imgOut = await imageProvider.generateImage({
      prompt: 'Futuristic quantum data center with neon fiber optics',
    });
    assert.equal(imgOut.mimeType, 'image/png');
    assert.ok(imgOut.caption.includes('Enhanced Prompt:'));
  });
});
