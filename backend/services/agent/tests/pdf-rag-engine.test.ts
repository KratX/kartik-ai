  it('reranks vector hits with hybrid semantic + BM25 lexical scoring and deduplicates near-identical chunks', () => {
    const hits: VectorSearchHit[] = [
      {
        chunkId: 'chk_noisy',
        fileId: 'file_1',
        userId: 'usr_1',
        documentTitle: 'architecture-spec.pdf',
        pageNumber: 1,
        textContent: 'General platform overview describing modern cloud services and customer growth initiatives.',
        score: 0.72,
      },
      {
        chunkId: 'chk_exact',
        fileId: 'file_1',
        userId: 'usr_1',
        documentTitle: 'architecture-spec.pdf',
        pageNumber: 4,
        textContent: 'Razorpay webhook verification computes HMAC-SHA256 strictly over rawBody bytes before JSON parsing.',
        score: 0.58,
      },
      {
        chunkId: 'chk_exact_dup',
        fileId: 'file_1',
        userId: 'usr_1',
        documentTitle: 'architecture-spec.pdf',
        pageNumber: 4,
        textContent: 'Razorpay webhook verification computes HMAC-SHA256 strictly over rawBody bytes before JSON parsing.',
        score: 0.57,
      },
    ];

    const ranked = rerankRagHits(
      'How does Razorpay webhook HMAC-SHA256 rawBody verification work?',
      hits,
      { topK: 4 },
    );

    // Exact keyword/technical match outranks noisier vector-only hit
    assert.equal(ranked[0]?.chunkId, 'chk_exact');
    assert.ok(ranked[0]!.hybridScore > ranked[1]!.hybridScore);
    // Near-duplicate on same page is suppressed (only 2 unique chunks remain)
    assert.equal(ranked.length, 2);
    assert.ok(ranked[0]!.excerpt.includes('HMAC-SHA256'));
  });

