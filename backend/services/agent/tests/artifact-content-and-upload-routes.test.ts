import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { describe, it } from 'node:test';
import {
  INTERNAL_AUTH_HEADERS,
  signUserContextAssertion,
} from '@kartik/shared/auth';
import { InMemoryObjectStorage } from '@kartik/shared/storage';
import {
  AgentGraphExecutor,
  buildPdfBinaryBuffer,
  createAgentRouter,
  DailyLiveBudgetGuard,
  FileIngestionAndArtifactService,
  InMemoryAgentRepository,
  InMemoryDailyBudgetStore,
  InMemoryVectorStore,
  LiveGeminiChatModelProvider,
  LiveGeminiCodingModelProvider,
  LiveGeminiEmbeddingProvider,
  LiveGeminiImageGenerationProvider,
  LiveGeminiPdfDocumentProvider,
  LiveGeminiPptPresentationProvider,
  LiveGeminiSearchProvider,
  LiveGeminiVisionProvider,
  loadAgentConfig,
} from '../src/index.js';

const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
const TEST_PRIVATE_PEM = privateKey
  .export({ type: 'pkcs8', format: 'pem' })
  .toString();
const TEST_PUBLIC_PEM = publicKey
  .export({ type: 'spki', format: 'pem' })
  .toString();

function createTestAgentStack() {
  const nowSec = 1_762_900_000;
  const config = loadAgentConfig({
    NODE_ENV: 'test',
    DATABASE_URL: 'postgresql://kartik:kartik@127.0.0.1:5432/kartik',
    REDIS_URL: 'redis://127.0.0.1:6379',
    USER_CONTEXT_PUBLIC_KEY: TEST_PUBLIC_PEM,
    INTERNAL_CALLER_TOKEN_CHAT: 'internal-secret-token-chat-to-agent',
    MOCK_AI: 'true',
    GEMINI_API_KEY: 'test-gemini-api-key-value',
    TAVILY_API_KEY: 'test-tavily-api-key',
    DAILY_LIVE_CALL_BUDGET: '25',
  });

  const repository = new InMemoryAgentRepository();
  const objectStorage = new InMemoryObjectStorage();
  const vectorStore = new InMemoryVectorStore();
  const embeddingProvider = new LiveGeminiEmbeddingProvider();

  const ingestionService = new FileIngestionAndArtifactService({
    config,
    repository,
    objectStorage,
    vectorStore,
    embeddingProvider,
  });

  const graphExecutor = new AgentGraphExecutor({
    config,
    budgetGuard: new DailyLiveBudgetGuard({
      store: new InMemoryDailyBudgetStore(),
      dailyLimit: 25,
      mockAiDefault: true,
    }),
    chatProvider: new LiveGeminiChatModelProvider(),
    codingProvider: new LiveGeminiCodingModelProvider(),
    searchProvider: new LiveGeminiSearchProvider(),
    embeddingProvider,
    imageProvider: new LiveGeminiImageGenerationProvider(),
    visionProvider: new LiveGeminiVisionProvider(),
    pdfProvider: new LiveGeminiPdfDocumentProvider(),
    pptProvider: new LiveGeminiPptPresentationProvider(),
    vectorStore,
    objectStorage,
    metadataStore: repository,
  });

  const router = createAgentRouter({
    config,
    repository,
    ingestionService,
    graphExecutor,
    nowSeconds: () => nowSec,
  });

  const mintUserHeader = (userId: string) =>
    signUserContextAssertion(
      {
        sub: userId,
        sessionId: `sess_${userId}`,
        aud: 'agent',
        traceId: 'trc_93a_test',
        nowSeconds: nowSec,
      },
      TEST_PRIVATE_PEM,
    );

  return { router, mintUserHeader };
}

describe('Phase 9.3.a — Binary File Upload (/files/upload) & Artifact Raw Content (/artifacts/:id/content) Routes', () => {
  it('accepts binary PDF uploads via POST /files/upload, extracts PDF pages automatically, and indexes vector chunks', async () => {
    const { router, mintUserHeader } = createTestAgentStack();
    const compiledPdf = buildPdfBinaryBuffer({
      title: 'Zero-Trust Service Authentication',
      subtitle: 'Ed25519 Signed Context Assertions',
      sections: [
        {
          heading: 'Gateway Session Introspection',
          content:
            'The API Gateway introspects the opaque session cookie once and signs an audience-scoped Ed25519 assertion.',
          bullets: ['Prevents confused-deputy horizontal privilege escalation'],
        },
      ],
      footer: 'Generated by Kartik.ai',
    });

    const uploadRes = await router.execute<{
      data: {
        fileId: string;
        mimeType: string;
        pageCount: number;
        chunkCount: number;
        status: string;
      };
    }>({
      method: 'POST',
      path: '/api/v1/files/upload',
      headers: {
        [INTERNAL_AUTH_HEADERS.USER_CONTEXT]: mintUserHeader('usr_upload_93a'),
        [INTERNAL_AUTH_HEADERS.TRACE_ID]: 'trc_upload_93a',
        [INTERNAL_AUTH_HEADERS.REQUEST_ID]: 'req_upload_93a_001',
      },
      body: {
        conversationId: 'conv_upload_93a',
        originalFilename: 'zero-trust.pdf',
        declaredMimeType: 'application/pdf',
        contentBase64: Buffer.from(compiledPdf.pdfBytes).toString('base64'),
      },
    });

    assert.equal(uploadRes.statusCode, 201);
    assert.equal(uploadRes.body.data.mimeType, 'application/pdf');
    assert.equal(uploadRes.body.data.status, 'ready');
    assert.ok(uploadRes.body.data.pageCount >= 1);
    assert.ok(uploadRes.body.data.chunkCount >= 1);
  });

  it('returns base64 binary payload and signed URL on GET /artifacts/:artifactId/content for PDF and PPTX artifacts and returns 404 on foreign lookup (Invariants #10 & #20)', async () => {
    const { router, mintUserHeader } = createTestAgentStack();

    // Generate a PDF artifact via internal execute
    const execPdfRes = await router.execute<{
      data: { artifactIds: string[] };
    }>({
      method: 'POST',
      path: '/internal/agent/execute',
      headers: {
        [INTERNAL_AUTH_HEADERS.SERVICE_CALLER]: 'chat',
        [INTERNAL_AUTH_HEADERS.SERVICE_TOKEN]: 'internal-secret-token-chat-to-agent',
        [INTERNAL_AUTH_HEADERS.TRACE_ID]: 'trc_pdf_93a',
        [INTERNAL_AUTH_HEADERS.REQUEST_ID]: 'req_pdf_93a_001',
      },
      body: {
        requestId: 'req_pdf_93a_001',
        traceId: 'trc_pdf_93a',
        userId: 'usr_owner_93a',
        conversationId: 'conv_93a',
        messageId: 'msg_93a_1',
        prompt: 'Generate a PDF architecture report on Raft consensus',
        preferredAgent: 'pdf',
      },
    });

    assert.equal(execPdfRes.statusCode, 200);
    const pdfArtifactId = execPdfRes.body.data.artifactIds[0]!;
    assert.ok(pdfArtifactId);

    // Owner fetches GET /artifacts/:artifactId/content
    const contentRes = await router.execute<{
      data: {
        artifact: { artifactId: string; artifactType: string; mimeType: string };
        download: { signedUrl: string };
        contentBase64: string;
      };
    }>({
      method: 'GET',
      path: `/api/v1/artifacts/${pdfArtifactId}/content`,
      headers: {
        [INTERNAL_AUTH_HEADERS.USER_CONTEXT]: mintUserHeader('usr_owner_93a'),
        [INTERNAL_AUTH_HEADERS.TRACE_ID]: 'trc_get_content_93a',
      },
    });

    assert.equal(contentRes.statusCode, 200);
    assert.equal(contentRes.body.data.artifact.artifactId, pdfArtifactId);
    assert.equal(contentRes.body.data.artifact.artifactType, 'pdf_document');
    assert.equal(contentRes.body.data.artifact.mimeType, 'application/pdf');
    assert.ok(contentRes.body.data.download.signedUrl.includes('X-Amz-Signature='));

    const decodedPdfBytes = Buffer.from(contentRes.body.data.contentBase64, 'base64');
    assert.equal(decodedPdfBytes.subarray(0, 8).toString('ascii'), '%PDF-1.4');

    // Foreign user lookup returns 404 NOT_FOUND (Invariant #20)
    const foreignRes = await router.execute<{
      error: { code: string };
    }>({
      method: 'GET',
      path: `/api/v1/artifacts/${pdfArtifactId}/content`,
      headers: {
        [INTERNAL_AUTH_HEADERS.USER_CONTEXT]: mintUserHeader('usr_intruder_93a'),
        [INTERNAL_AUTH_HEADERS.TRACE_ID]: 'trc_intruder_93a',
      },
    });
    assert.equal(foreignRes.statusCode, 404);
    assert.equal(foreignRes.body.error.code, 'NOT_FOUND');
  });
});
