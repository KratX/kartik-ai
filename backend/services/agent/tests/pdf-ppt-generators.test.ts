import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { InMemoryObjectStorage } from '@kartik/shared/storage';
import {
  AgentGraphExecutor,
  DailyLiveBudgetGuard,
  InMemoryAgentRepository,
  InMemoryDailyBudgetStore,
  InMemoryVectorStore,
  MockChatModelProvider,
  MockCodingModelProvider,
  MockEmbeddingProvider,
  MockImageGenerationProvider,
  MockPdfDocumentProvider,
  MockPptPresentationProvider,
  MockSearchProvider,
  MockVisionProvider,
  buildPdfBinaryBuffer,
  buildPptxBinaryBuffer,
  loadAgentConfig,
  routePromptToSpecialist,
  validatePdfDocumentSpec,
  validatePptPresentationSpec,
} from '../src/index.js';

import crypto from 'node:crypto';

const { publicKey } = crypto.generateKeyPairSync('ed25519');
const TEST_PUBLIC_PEM = publicKey.export({ type: 'spki', format: 'pem' }).toString();

function createTestAgentConfig() {
  return loadAgentConfig({
    NODE_ENV: 'test',
    DATABASE_URL: 'postgresql://kartik:kartik@127.0.0.1:5432/kartik',
    REDIS_URL: 'redis://127.0.0.1:6379',
    USER_CONTEXT_PUBLIC_KEY: TEST_PUBLIC_PEM,
    INTERNAL_CALLER_TOKEN_CHAT: 'internal-secret-token-chat-to-agent',
    MOCK_AI: 'true',
    GEMINI_API_KEY: 'test-gemini-api-key-value',
    TAVILY_API_KEY: 'test-tavily-api-key',
    DAILY_LIVE_CALL_BUDGET: '25',
  });
}

describe('@kartik/agent — Phase 10 PDF & PPTX Generators & Schemas (Micro-step 9.1.a)', () => {
  it('compiles a validated PdfDocumentSpec into a standards-compliant %PDF-1.4 binary with xref, trailer, and page footer', () => {
    const spec = validatePdfDocumentSpec({
      title: 'Distributed Consensus & Raft Protocol',
      subtitle: 'Fault-Tolerant State Machines in Production',
      sections: [
        {
          heading: 'Leader Election & Term Monotonicity',
          content:
            'Raft partitions time into terms of arbitrary length, numbered with consecutive integers. Each term begins with an election where candidates request votes.',
          bullets: [
            'At most one leader can be elected in a given term',
            'Heartbeats maintain authority and prevent unnecessary elections',
          ],
        },
        {
          heading: 'Log Replication & Safety Guarantees',
          content:
            'Once a leader has been elected, it begins servicing client requests by appending entries to its replicated log.',
          bullets: [
            'Log Matching Property guarantees identical prefixes',
            'Committed entries are durable across a majority of nodes',
          ],
        },
      ],
      footer: 'Generated by Kartik.ai',
    });

    const compiled = buildPdfBinaryBuffer(spec);
    assert.ok(compiled.pdfBytes.byteLength > 400);
    assert.equal(compiled.pageCount, 1);

    const ascii = compiled.pdfBytes.toString('ascii');
    assert.ok(ascii.startsWith('%PDF-1.4\n'), 'PDF must start with %PDF-1.4 header');
    assert.ok(ascii.includes('/Type /Catalog'), 'PDF must include Catalog object');
    assert.ok(ascii.includes('/Type /Page'), 'PDF must include Page object');
    assert.ok(ascii.includes('Generated by Kartik.ai'), 'PDF must include footer text');
    assert.ok(ascii.includes('Page 1 of 1'), 'PDF must include page numbering');
    assert.ok(ascii.includes('\nxref\n'), 'PDF must include xref table');
    assert.ok(ascii.trimEnd().endsWith('%%EOF'), 'PDF must end with %%EOF marker');
  });

  it('truncates oversized PDF and PPT text inputs predictably rather than producing corrupt files', () => {
    const hugeTitle = 'A'.repeat(500);
    const hugeParagraph = 'Word '.repeat(1000);
    const spec = validatePdfDocumentSpec({
      title: hugeTitle,
      subtitle: 'Oversized Input Test',
      sections: Array.from({ length: 20 }, (_, i) => ({
        heading: `Section ${i + 1}: ${hugeTitle}`,
        content: hugeParagraph,
        bullets: ['Bullet '.repeat(80)],
      })),
    });

    assert.ok(spec.title.length <= 140);
    assert.equal(spec.sections.length, 12); // Capped at MAX_PDF_SECTIONS (12)

    const compiled = buildPdfBinaryBuffer(spec);
    assert.ok(compiled.pageCount >= 2, 'Long multi-section input must paginate cleanly across multiple pages');
    assert.ok(compiled.pdfBytes.toString('ascii').trimEnd().endsWith('%%EOF'));
  });

  it('compiles a validated PptPresentationSpec into an OpenXML .pptx ZIP archive (PK\\x03\\x04) with Cover, 6 Content Slides, and Thank You Slide', () => {
    const rawJson = JSON.stringify({
      title: 'Microservices & Event-Driven Architecture',
      subtitle: 'Scalable Patterns for Cloud-Native Systems',
      slides: Array.from({ length: 6 }, (_, idx) => ({
        title: `Core Pillar ${idx + 1}`,
        subtitle: `Key Design Pattern ${idx + 1}`,
        bullets: [
          `Primary capability for pillar ${idx + 1}`,
          `Operational guardrail for pillar ${idx + 1}`,
        ],
      })),
    });

    const spec = validatePptPresentationSpec(rawJson);
    // 1 Cover + 6 Content + 1 Thank You = 8 total slides
    assert.equal(spec.slides.length, 8);
    assert.equal(spec.slides[0]?.kind, 'cover');
    assert.equal(spec.slides[7]?.kind, 'thank_you');

    const compiled = buildPptxBinaryBuffer(spec);
    assert.equal(compiled.slideCount, 8);
    assert.ok(compiled.pptxBytes.byteLength > 1000);

    // Check ZIP magic bytes PK\x03\x04
    assert.equal(compiled.pptxBytes[0], 0x50); // 'P'
    assert.equal(compiled.pptxBytes[1], 0x4b); // 'K'
    assert.equal(compiled.pptxBytes[2], 0x03);
    assert.equal(compiled.pptxBytes[3], 0x04);

    const zipAscii = compiled.pptxBytes.toString('utf8');
    assert.ok(zipAscii.includes('[Content_Types].xml'));
    assert.ok(zipAscii.includes('ppt/presentation.xml'));
    assert.ok(zipAscii.includes('ppt/slides/slide1.xml'));
    assert.ok(zipAscii.includes('ppt/slides/slide8.xml'));
    assert.ok(zipAscii.includes('Microservices &amp; Event-Driven Architecture'));
  });

  it('rejects malformed or empty PDF and PPT model output with ARTIFACT_INVALID', () => {
    assert.throws(
      () => validatePdfDocumentSpec('{not valid json'),
      (err: unknown) => (err as { code?: string }).code === 'ARTIFACT_INVALID',
    );
    assert.throws(
      () => validatePdfDocumentSpec({ title: 'Missing Sections', sections: [] }),
      (err: unknown) => (err as { code?: string }).code === 'ARTIFACT_INVALID',
    );
    assert.throws(
      () => validatePptPresentationSpec({ title: 'Missing Slides', slides: [] }),
      (err: unknown) => (err as { code?: string }).code === 'ARTIFACT_INVALID',
    );
  });

  it('routes and executes pdf and ppt specialist turns through AgentGraphExecutor, storing private objects and replaying idempotently', async () => {
    assert.equal(
      routePromptToSpecialist({ prompt: 'Generate a PDF report on Redis caching' }),
      'pdf',
    );
    assert.equal(
      routePromptToSpecialist({ prompt: 'Create a PPT presentation on Kubernetes' }),
      'ppt',
    );

    const config = createTestAgentConfig();
    const repo = new InMemoryAgentRepository();
    const objectStorage = new InMemoryObjectStorage();
    const executor = new AgentGraphExecutor({
      config,
      budgetGuard: new DailyLiveBudgetGuard({
        store: new InMemoryDailyBudgetStore(),
        dailyLimit: 25,
        mockAiDefault: true,
      }),
      chatProvider: new MockChatModelProvider(),
      codingProvider: new MockCodingModelProvider(),
      searchProvider: new MockSearchProvider(),
      embeddingProvider: new MockEmbeddingProvider(),
      imageProvider: new MockImageGenerationProvider(),
      visionProvider: new MockVisionProvider(),
      pdfProvider: new MockPdfDocumentProvider(),
      pptProvider: new MockPptPresentationProvider(),
      vectorStore: new InMemoryVectorStore(),
      objectStorage,
      metadataStore: repo,
    });

    // 1. Execute PDF generation turn
    const pdfRes = await executor.execute({
      requestId: 'req_pdf_turn_001',
      traceId: 'trace_pdf_001',
      userId: 'usr_owner_01',
      conversationId: 'conv_01',
      messageId: 'msg_pdf_01',
      prompt: 'Generate a PDF report on Zero-Trust Microservices',
    });

    assert.equal(pdfRes.agent, 'pdf');
    assert.equal(pdfRes.artifactIds?.length, 1);
    const pdfArtifact = await repo.getArtifactById('usr_owner_01', pdfRes.artifactIds![0]!);
    assert.ok(pdfArtifact);
    assert.equal(pdfArtifact.artifactType, 'pdf_document');
    assert.equal(pdfArtifact.mimeType, 'application/pdf');
    assert.ok(pdfArtifact.sizeBytes > 400);

    const signedPdfDownload = await objectStorage.createSignedDownloadUrl({
      key: pdfArtifact.storageKey,
      requesterUserId: 'usr_owner_01',
      ttlSeconds: 300,
    });
    assert.ok(signedPdfDownload.signedUrl.includes('X-Amz-Signature='));

    // 2. Execute PPT generation turn
    const pptRes = await executor.execute({
      requestId: 'req_ppt_turn_001',
      traceId: 'trace_ppt_001',
      userId: 'usr_owner_01',
      conversationId: 'conv_01',
      messageId: 'msg_ppt_01',
      prompt: 'Create a PPT presentation on LangGraph Multi-Agent Systems',
    });

    assert.equal(pptRes.agent, 'ppt');
    assert.equal(pptRes.artifactIds?.length, 1);
    const pptArtifact = await repo.getArtifactById('usr_owner_01', pptRes.artifactIds![0]!);
    assert.ok(pptArtifact);
    assert.equal(pptArtifact.artifactType, 'ppt_presentation');
    assert.equal(
      pptArtifact.mimeType,
      'application/vnd.openxmlformats-officedocument.presentationml.presentation',
    );
    assert.equal(pptArtifact.filesManifest.length, 1);
    assert.equal(pptArtifact.filesManifest[0]?.path, 'slides-spec.json');

    // Verify idempotent replay on duplicate requestId
    const pptReplay = await executor.execute({
      requestId: 'req_ppt_turn_001',
      traceId: 'trace_ppt_002',
      userId: 'usr_owner_01',
      conversationId: 'conv_01',
      messageId: 'msg_ppt_01',
      prompt: 'Create a PPT presentation on LangGraph Multi-Agent Systems',
    });
    assert.deepEqual(pptReplay.artifactIds, pptRes.artifactIds);
  });
});
