/**
 * @kartik/agent/rag/loaders — Production Multi-Tier PDF Text & Page Extractor (Fix #18 + Fix #30).
 *
 * Extracts clean, reading-order page-by-page text from ANY uploaded `%PDF-1.x` / `%PDF-2.0` binary:
 * - Tier 1: Mozilla `pdfjs-dist` (`pdfjs-dist/legacy/build/pdf.mjs`) — handles real-world PDFs from
 *   Google Docs, Chrome, Word, LaTeX, Acrobat, Figma, and Canva including `/ObjStm` compressed object
 *   streams, `/ToUnicode` CMap CID fonts, Identity-H, WinAnsi/MacRoman encodings, and exact `/Pages`
 *   tree ordering with `(x, y)` coordinate reading-order line reconstruction.
 * - Tier 2: Hardened binary stream extractor (`extractTextPagesFromPdfBytes`) — zero-dependency
 *   synchronous parser for synthetic/minimal PDFs without xref tables, with raw PDF syntax filtering
 *   so structural object metadata (`1 0 obj << /Type /Catalog >>`) is NEVER indexed as document prose.
 * - Tier 3: Quality assessment (`assessPdfExtractionQuality`) + optional Gemini native multimodal PDF
 *   OCR fallback (`PdfMultimodalExtractor`) for scanned / image-only / garbled-font PDFs.
 */

import zlib from 'node:zlib';
import { AppError } from '@kartik/shared/errors';
import type { PdfMultimodalExtractor } from '../../models/index.js';
import type { PdfPageText } from '../index.js';

export interface PdfExtractionQualityReport {
  readonly totalPages: number;
  readonly nonEmptyPages: number;
  readonly totalReadableChars: number;
  readonly garbledRatio: number;
  readonly needsMultimodalOcr: boolean;
}

export interface PdfExtractionResult {
  readonly pages: readonly PdfPageText[];
  readonly totalPageCount: number;
  readonly method: 'pdfjs' | 'stream_fallback' | 'gemini_ocr' | 'empty';
}

function unescapePdfLiteralString(raw: string): string {
  // Handle PDF line continuations (backslash followed by CR/LF)
  let text = raw.replace(/\\(?:\r\n|\r|\n)/g, '');
  // Decode octal escape sequences (\000 - \377)
  text = text.replace(/\\([0-7]{1,3})/g, (_match, octal: string) => {
    const code = Number.parseInt(octal, 8);
    return Number.isFinite(code) && code >= 9 && code <= 255
      ? String.fromCharCode(code)
      : '';
  });
  // Decode standard PDF escape characters
  return text
    .replace(/\\n/g, '\n')
    .replace(/\\r/g, '\n')
    .replace(/\\t/g, ' ')
    .replace(/\\b/g, '')
    .replace(/\\f/g, '\n')
    .replace(/\\\(/g, '(')
    .replace(/\\\)/g, ')')
    .replace(/\\\\/g, '\\');
}

function decodePdfHexString(hexRaw: string): string {
  const clean = hexRaw.replace(/[^0-9a-fA-F]/g, '');
  if (clean.length === 0) {
    return '';
  }
  const padded = clean.length % 2 === 1 ? `${clean}0` : clean;
  const bytes = Buffer.from(padded, 'hex');

  // UTF-16BE with BOM (0xFE 0xFF) — standard in modern Google Docs / Chrome / Word PDFs
  if (bytes.length >= 2 && bytes[0] === 0xfe && bytes[1] === 0xff) {
    const chars: string[] = [];
    for (let i = 2; i + 1 < bytes.length; i += 2) {
      const codeUnit = ((bytes[i] ?? 0) << 8) | (bytes[i + 1] ?? 0);
      if (codeUnit >= 0x20 || codeUnit === 0x0a || codeUnit === 0x09) {
        chars.push(String.fromCharCode(codeUnit));
      }
    }
    return chars.join('');
  }

  // Standard single-byte PDFDocEncoding / Latin-1 hex string
  return bytes
    .toString('latin1')
    .replace(/[^\x09\x0A\x20-\x7E\xA0-\xFF]/g, '');
}

function isRunningBoilerplate(line: string): boolean {
  const trimmed = line.trim();
  if (!trimmed) {
    return true;
  }
  if (/^Generated by Kartik\.ai/i.test(trimmed)) {
    return true;
  }
  if (/^Page\s+\d+\s*(?:of|\/)\s*\d+$/i.test(trimmed)) {
    return true;
  }
  return false;
}

function decodeTjArray(arrayInner: string): string {
  const tokenRegex =
    /\(([^()\\]*(?:\\.[^()\\]*)*)\)|<([0-9a-fA-F\s]+)>|(-?\d+(?:\.\d+)?)/g;
  const parts: string[] = [];
  let match: RegExpExecArray | null;

  while ((match = tokenRegex.exec(arrayInner)) !== null) {
    if (match[1] !== undefined) {
      parts.push(unescapePdfLiteralString(match[1]));
    } else if (match[2] !== undefined) {
      parts.push(decodePdfHexString(match[2]));
    } else if (match[3] !== undefined) {
      // In PDF TJ arrays, negative numbers shift text right (larger negative = wider gap/space)
      const kerning = Number.parseFloat(match[3]);
      if (Number.isFinite(kerning) && kerning <= -120) {
        const last = parts[parts.length - 1] ?? '';
        if (last && !/\s$/.test(last)) {
          parts.push(' ');
        }
      }
    }
  }

  return parts.join('');
}

function looksLikeNonTextStream(streamAscii: string): boolean {
  // Skip XML/XMP metadata packets and obvious font/ICC binary blobs without text-showing ops
  const trimmed = streamAscii.trimStart();
  if (trimmed.startsWith('<?xpacket') || trimmed.startsWith('<x:xmpmeta')) {
    return true;
  }
  const hasTextOp =
    /(?:Tj|TJ)\b/.test(streamAscii) ||
    /\)\s*['"]/.test(streamAscii) ||
    />\s*['"]/.test(streamAscii);
  return !hasTextOp;
}

/**
 * Detects raw PDF object/dictionary syntax so structural PDF metadata
 * (`1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj`) is NEVER mistakenly indexed as prose.
 */
export function looksLikeRawPdfSyntax(text: string): boolean {
  const trimmed = text.trim();
  if (!trimmed) {
    return true;
  }
  const syntaxTokens =
    trimmed.match(
      /\b(?:endobj|endstream|startxref|xref|trailer|FlateDecode|ASCII85Decode|MediaBox|FontDescriptor|CIDFontType|ToUnicode|XObject)\b|\d+\s+\d+\s+obj\b|\/(?:Type|Catalog|Pages|Kids|Count|Filter|Length|Resources|Font|Subtype|BaseFont|Encoding)\b/g,
    ) ?? [];
  const words = trimmed.split(/\s+/).filter(Boolean);
  if (words.length === 0) {
    return true;
  }
  // If >= 3 structural tokens appear and account for a significant portion of tokens, reject as raw PDF syntax
  if (syntaxTokens.length >= 3 && syntaxTokens.length / words.length >= 0.12) {
    return true;
  }
  if (/^(?:\d+\s+\d+\s+obj\b|<<\s*\/)/.test(trimmed) && syntaxTokens.length >= 2) {
    return true;
  }
  return false;
}

/**
 * Evaluates extracted PDF pages to determine whether text extraction succeeded cleanly
 * or if the PDF appears to be scanned / image-only / corrupted-font and needs OCR fallback.
 */
export function assessPdfExtractionQuality(
  pages: readonly PdfPageText[],
): PdfExtractionQualityReport {
  const totalPages = pages.length;
  let nonEmptyPages = 0;
  let totalReadableChars = 0;
  let totalNonSpaceChars = 0;
  let suspiciousChars = 0;

  for (const page of pages) {
    const clean = page.text.trim();
    if (!clean || looksLikeRawPdfSyntax(clean)) {
      continue;
    }
    const alphaNum = clean.match(/[A-Za-z0-9\u00C0-\u024F\u0900-\u097F]/g)?.length ?? 0;
    const nonSpace = clean.replace(/\s+/g, '');
    const suspicious =
      nonSpace.match(/[\uFFFD\u0000-\u0008\u000B\u000C\u000E-\u001F]/g)?.length ?? 0;
    // Also detect garbled single-character symbol runs from broken CID/CMap decoders
    const strangeSymbols =
      nonSpace.match(/[^A-Za-z0-9\u00C0-\u024F\u0900-\u097F.,;:!?'"()\[\]{}\-+/*@#$%&=_<>|\\~`^°€£¥₹—–•·]/g)
        ?.length ?? 0;

    if (alphaNum >= 12) {
      nonEmptyPages += 1;
    }
    totalReadableChars += alphaNum;
    totalNonSpaceChars += nonSpace.length;
    suspiciousChars += suspicious + strangeSymbols;
  }

  const garbledRatio =
    totalNonSpaceChars > 0 ? Number((suspiciousChars / totalNonSpaceChars).toFixed(4)) : 1;

  const needsMultimodalOcr =
    totalPages === 0 ||
    nonEmptyPages === 0 ||
    totalReadableChars < 24 ||
    (totalNonSpaceChars >= 40 && garbledRatio > 0.35);

  return Object.freeze({
    totalPages,
    nonEmptyPages,
    totalReadableChars,
    garbledRatio,
    needsMultimodalOcr,
  });
}

/**
 * Parses Gemini multimodal PDF OCR output delimited by `=== PAGE N ===` markers
 * into ordered `PdfPageText[]` records.
 */
export function parseOcrPagesFromGeminiText(rawText: string): readonly PdfPageText[] {
  const trimmed = rawText.trim();
  if (!trimmed) {
    return Object.freeze([]);
  }

  const pageMarkerRegex = /(?:^|\n)\s*(?:={2,}\s*PAGE\s+(\d+)\s*={2,}|#{1,3}\s*Page\s+(\d+)\b[^\n]*)\s*(?:\n|$)/gi;
  const markers: Array<{ pageNumber: number; matchStart: number; contentStart: number }> = [];
  let match: RegExpExecArray | null;

  while ((match = pageMarkerRegex.exec(trimmed)) !== null) {
    const numStr = match[1] ?? match[2] ?? '';
    const pageNumber = Number.parseInt(numStr, 10);
    if (Number.isInteger(pageNumber) && pageNumber >= 1) {
      markers.push({
        pageNumber,
        matchStart: match.index,
        contentStart: match.index + match[0].length,
      });
    }
  }

  if (markers.length === 0) {
    return Object.freeze([
      Object.freeze({
        pageNumber: 1,
        text: trimmed,
      }),
    ]);
  }

  const pages: PdfPageText[] = [];
  for (let i = 0; i < markers.length; i += 1) {
    const curr = markers[i]!;
    const nextStart = i + 1 < markers.length ? markers[i + 1]!.matchStart : trimmed.length;
    const text = trimmed.slice(curr.contentStart, nextStart).trim();
    if (text.length > 0) {
      pages.push(
        Object.freeze({
          pageNumber: curr.pageNumber,
          text,
        }),
      );
    }
  }

  if (pages.length === 0) {
    return Object.freeze([
      Object.freeze({
        pageNumber: 1,
        text: trimmed,
      }),
    ]);
  }

  return Object.freeze(pages);
}

/**
 * Extracts readable, line-ordered text from a single decoded PDF content stream.
 */
export function extractTextFromStreamContent(streamAscii: string): string {
  if (looksLikeNonTextStream(streamAscii)) {
    return '';
  }

  // Unified ordered scanner across literal Tj/'/", hex Tj/'/", array TJ, and line-break positioning ops
  const opRegex =
    /\(([^()\\]*(?:\\.[^()\\]*)*)\)\s*(?:Tj|'|")|<([0-9a-fA-F\s]+)>\s*(?:Tj|'|")|\[((?:[^[\]]|\r|\n)*?)\]\s*TJ|(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(?:Td|TD)\b|\bT\*\b|(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)\s+Tm\b|\bET\b/g;

  const lines: string[] = [];
  let currentLine = '';
  let lastTmY: number | null = null;

  const flushLine = () => {
    const cleaned = currentLine.replace(/[ \t]+/g, ' ').trim();
    if (cleaned && !isRunningBoilerplate(cleaned)) {
      lines.push(cleaned);
    }
    currentLine = '';
  };

  const appendText = (fragment: string) => {
    if (!fragment) {
      return;
    }
    if (fragment.includes('\n')) {
      const splitLines = fragment.split('\n');
      for (let i = 0; i < splitLines.length; i += 1) {
        const seg = splitLines[i] ?? '';
        if (i > 0) {
          flushLine();
        }
        if (seg) {
          currentLine =
            currentLine && !/\s$/.test(currentLine) && !/^\s/.test(seg)
              ? `${currentLine} ${seg}`
              : `${currentLine}${seg}`;
        }
      }
      return;
    }

    if (
      currentLine &&
      !/\s$/.test(currentLine) &&
      !/^\s/.test(fragment) &&
      !/^[,.;:!?)\]}]/.test(fragment)
    ) {
      currentLine += ` ${fragment}`;
    } else {
      currentLine += fragment;
    }
  };

  let match: RegExpExecArray | null;
  while ((match = opRegex.exec(streamAscii)) !== null) {
    if (match[1] !== undefined) {
      appendText(unescapePdfLiteralString(match[1]));
    } else if (match[2] !== undefined) {
      appendText(decodePdfHexString(match[2]));
    } else if (match[3] !== undefined) {
      appendText(decodeTjArray(match[3]));
    } else if (match[4] !== undefined && match[5] !== undefined) {
      // Td / TD vertical shift indicates new line or paragraph
      const dy = Math.abs(Number.parseFloat(match[5]));
      if (dy >= 4) {
        flushLine();
      }
    } else if (match[11] !== undefined) {
      // Tm matrix: 6th number is vertical Y coordinate
      const tmY = Number.parseFloat(match[11]);
      if (lastTmY !== null && Math.abs(tmY - lastTmY) >= 4) {
        flushLine();
      }
      lastTmY = tmY;
    } else if (match[0] === 'T*' || match[0] === 'ET') {
      flushLine();
      if (match[0] === 'ET') {
        lastTmY = null;
      }
    }
  }
  flushLine();

  if (lines.length === 0) {
    return '';
  }

  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

function tryDecompressPdfStream(rawStreamBody: string): string {
  const trimmed = rawStreamBody.replace(/^[\r\n]+/, '').replace(/[\r\n]+$/, '');
  const compressedBuf = Buffer.from(trimmed, 'latin1');

  try {
    return zlib.inflateSync(compressedBuf).toString('latin1');
  } catch {
    // Fallback to raw deflate (RFC 1951) if zlib header is absent
    try {
      return zlib.inflateRawSync(compressedBuf).toString('latin1');
    } catch {
      return rawStreamBody;
    }
  }
}

/**
 * Synchronous binary `.pdf` byte-stream parser for minimal/synthetic PDFs and unit tests.
 * Never returns raw PDF object syntax (`1 0 obj << /Type /Catalog >>`) as fake document text.
 */
export function extractTextPagesFromPdfBytes(pdfBytes: Uint8Array): readonly PdfPageText[] {
  const buf = Buffer.from(pdfBytes);
  const rawLatin1 = buf.toString('latin1');

  // Locate all stream ... endstream blocks (tolerant of CRLF, LF, or trailing whitespace)
  const pages: PdfPageText[] = [];
  const streamRegex = /stream[ \t]*\r?\n([\s\S]*?)\r?\n?endstream/g;
  let match: RegExpExecArray | null;
  let pageCounter = 1;

  while ((match = streamRegex.exec(rawLatin1)) !== null) {
    const rawStreamBody = match[1] ?? '';
    let decodedAscii = rawStreamBody;

    // Attempt FlateDecode decompression when raw stream does not directly expose text operators
    if (looksLikeNonTextStream(rawStreamBody)) {
      decodedAscii = tryDecompressPdfStream(rawStreamBody);
    }

    const extracted = extractTextFromStreamContent(decodedAscii);
    if (extracted.length > 0 && !looksLikeRawPdfSyntax(extracted)) {
      pages.push(
        Object.freeze({
          pageNumber: pageCounter++,
          text: extracted,
        }),
      );
    }
  }

  if (pages.length > 0) {
    return Object.freeze(pages);
  }

  // Fallback ONLY for simple plain-text PDF fixtures used in minimal tests (never raw PDF object dumps)
  const fallbackText = buf
    .toString('utf8')
    .replace(/%PDF-[0-9.]+/g, ' ')
    .replace(/%%EOF/g, ' ')
    .replace(/[^\x20-\x7E\n]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  if (fallbackText.length >= 8 && !looksLikeRawPdfSyntax(fallbackText)) {
    return Object.freeze([
      Object.freeze({
        pageNumber: 1,
        text: fallbackText,
      }),
    ]);
  }

  return Object.freeze([]);
}

interface PdfJsTextItem {
  readonly str?: string;
  readonly hasEOL?: boolean;
  readonly transform?: readonly number[];
  readonly width?: number;
  readonly height?: number;
}

/**
 * Reconstructs clean reading-order lines and paragraphs from a PDF.js page's text items
 * using `(x, y)` baseline coordinates and `hasEOL` flags so tables and multi-line layouts stay intact.
 */
function reconstructPageTextFromPdfJsItems(items: readonly PdfJsTextItem[]): string {
  const lines: string[] = [];
  let currentLine = '';
  let lastY: number | null = null;
  let lastRightX: number | null = null;
  let lastHeight = 10;

  const flushLine = (addParagraphGap = false) => {
    const cleaned = currentLine.replace(/[ \t]+/g, ' ').trim();
    if (cleaned && !isRunningBoilerplate(cleaned)) {
      lines.push(cleaned);
      if (addParagraphGap && lines[lines.length - 1] !== '') {
        lines.push('');
      }
    }
    currentLine = '';
    lastRightX = null;
  };

  for (const item of items) {
    const rawStr = typeof item.str === 'string' ? item.str : '';
    const transform = Array.isArray(item.transform) ? item.transform : null;
    const x = transform && typeof transform[4] === 'number' ? transform[4] : null;
    const y = transform && typeof transform[5] === 'number' ? transform[5] : null;
    const itemHeight =
      typeof item.height === 'number' && item.height > 1
        ? item.height
        : transform && typeof transform[3] === 'number' && Math.abs(transform[3]) > 1
          ? Math.abs(transform[3])
          : lastHeight;

    if (y !== null && lastY !== null) {
      const dy = Math.abs(y - lastY);
      const lineThreshold = Math.max(3, Math.min(itemHeight, lastHeight) * 0.45);
      if (dy > lineThreshold) {
        const isParagraphBreak = dy > Math.max(16, Math.max(itemHeight, lastHeight) * 1.55);
        flushLine(isParagraphBreak);
      }
    }

    if (rawStr.length > 0) {
      const needsGap =
        currentLine.length > 0 &&
        !/\s$/.test(currentLine) &&
        !/^\s/.test(rawStr) &&
        !/^[,.;:!?)\]}]/.test(rawStr) &&
        (lastRightX === null ||
          x === null ||
          x - lastRightX > Math.max(1.5, itemHeight * 0.16));

      currentLine += needsGap ? ` ${rawStr}` : rawStr;
    }

    if (y !== null) {
      lastY = y;
    }
    if (x !== null) {
      const itemWidth = typeof item.width === 'number' && item.width >= 0 ? item.width : 0;
      lastRightX = x + itemWidth;
    }
    lastHeight = itemHeight;

    if (item.hasEOL) {
      flushLine(false);
    }
  }
  flushLine(false);

  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

/**
 * Tier-1 async extractor using Mozilla `pdfjs-dist` (`legacy/build/pdf.mjs`) with automatic
 * fallback to our hardened binary stream parser and optional Gemini native PDF OCR for scanned PDFs.
 */
export async function extractPdfPagesAsync(
  pdfBytes: Uint8Array,
  options?: {
    readonly maxPdfPages?: number;
    readonly ocrExtractor?: PdfMultimodalExtractor;
    readonly filename?: string;
  },
): Promise<PdfExtractionResult> {
  const maxPdfPages = options?.maxPdfPages ?? 50;
  let pdfJsPages: PdfPageText[] = [];
  let detectedPageCount = 0;
  let pdfJsSucceeded = false;

  try {
    const pdfjs = (await import('pdfjs-dist/legacy/build/pdf.mjs')) as {
      getDocument: (params: Record<string, unknown>) => {
        promise: Promise<{
          numPages: number;
          getPage: (n: number) => Promise<{
            getTextContent: () => Promise<{ items: readonly PdfJsTextItem[] }>;
          }>;
        }>;
        destroy?: () => Promise<void>;
      };
    };

    const loadingTask = pdfjs.getDocument({
      data: new Uint8Array(pdfBytes),
      verbosity: 0,
      isEvalSupported: false,
      disableFontFace: true,
      useSystemFonts: true,
      useWorkerFetch: false,
    });

    try {
      const doc = await loadingTask.promise;
      detectedPageCount = doc.numPages;

      if (doc.numPages > maxPdfPages) {
        throw new AppError(
          'VALIDATION_FAILED',
          `PDF page count (${doc.numPages}) exceeds MAX_PDF_PAGES (${maxPdfPages})`,
          { details: { pageCount: [`Maximum ${maxPdfPages} pages allowed`] } },
        );
      }

      for (let p = 1; p <= doc.numPages; p += 1) {
        const page = await doc.getPage(p);
        const textContent = await page.getTextContent();
        const reconstructed = reconstructPageTextFromPdfJsItems(textContent.items ?? []);
        if (reconstructed.length > 0 && !looksLikeRawPdfSyntax(reconstructed)) {
          pdfJsPages.push(
            Object.freeze({
              pageNumber: p,
              text: reconstructed,
            }),
          );
        }
      }
      pdfJsSucceeded = true;
    } finally {
      if (typeof loadingTask.destroy === 'function') {
        await loadingTask.destroy().catch(() => {});
      }
    }
  } catch (err) {
    // Re-throw explicit validation errors (e.g. MAX_PDF_PAGES exceeded)
    if (err instanceof AppError) {
      throw err;
    }
    pdfJsSucceeded = false;
  }

  // Evaluate Tier-1 quality
  const pdfJsQuality = assessPdfExtractionQuality(pdfJsPages);
  if (pdfJsSucceeded && !pdfJsQuality.needsMultimodalOcr && pdfJsPages.length > 0) {
    return Object.freeze({
      pages: Object.freeze(pdfJsPages),
      totalPageCount: Math.max(detectedPageCount, pdfJsPages.length),
      method: 'pdfjs',
    });
  }

  // Tier-2: Synchronous stream extractor fallback (handles minimal synthetic PDFs without xref tables)
  const streamPages = extractTextPagesFromPdfBytes(pdfBytes);
  const streamQuality = assessPdfExtractionQuality(streamPages);
  if (streamPages.length > 0 && !streamQuality.needsMultimodalOcr) {
    if (streamPages.length > maxPdfPages) {
      throw new AppError(
        'VALIDATION_FAILED',
        `PDF page count (${streamPages.length}) exceeds MAX_PDF_PAGES (${maxPdfPages})`,
        { details: { pageCount: [`Maximum ${maxPdfPages} pages allowed`] } },
      );
    }
    return Object.freeze({
      pages: streamPages,
      totalPageCount: Math.max(detectedPageCount, streamPages.length),
      method: 'stream_fallback',
    });
  }

  // Tier-3: Gemini native multimodal PDF OCR fallback for scanned / image-only / garbled-font PDFs
  if (options?.ocrExtractor && pdfBytes.byteLength <= 12 * 1024 * 1024) {
    try {
      const ocrPages = await options.ocrExtractor.extractPagesFromPdfBytes({
        pdfBytes,
        filename: options.filename,
        maxPages: maxPdfPages,
      });
      const ocrQuality = assessPdfExtractionQuality(ocrPages);
      if (ocrPages.length > 0 && !ocrQuality.needsMultimodalOcr) {
        return Object.freeze({
          pages: Object.freeze(ocrPages),
          totalPageCount: Math.max(detectedPageCount, ocrPages.length),
          method: 'gemini_ocr',
        });
      }
    } catch {
      // Fall through to best partial text or empty result below
    }
  }

  // Return partial usable text if either tier found something readable (e.g. short 1-line PDF)
  if (pdfJsPages.length > 0 && pdfJsQuality.totalReadableChars > 0) {
    return Object.freeze({
      pages: Object.freeze(pdfJsPages),
      totalPageCount: Math.max(detectedPageCount, pdfJsPages.length),
      method: 'pdfjs',
    });
  }
  if (streamPages.length > 0 && streamQuality.totalReadableChars > 0) {
    return Object.freeze({
      pages: streamPages,
      totalPageCount: Math.max(detectedPageCount, streamPages.length),
      method: 'stream_fallback',
    });
  }

  return Object.freeze({
    pages: Object.freeze([]),
    totalPageCount: Math.max(detectedPageCount, 1),
    method: 'empty',
  });
}
