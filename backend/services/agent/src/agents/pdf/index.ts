function renderSectionTable(
  canvas: PdfPageCanvas,
  table: PdfTableSpec,
  theme: PdfThemePalette,
): void {
  const colCount = table.headers.length;
  if (colCount < 2 || table.rows.length === 0) return;

  const colWidth = CONTENT_WIDTH / colCount;
  const maxCharsPerCell = Math.max(10, Math.floor((colWidth - 12) / 5.0));
  const headerHeight = 22;

  // Pre-wrap rows so we know exact height and can paginate cleanly row-by-row
  const wrappedRows = table.rows.map((row) => {
    const wrappedCells = row.map((cell) => wrapTextToLines(cell, maxCharsPerCell).slice(0, 3));
    const maxLines = Math.max(1, ...wrappedCells.map((c) => c.length));
    const rowHeight = maxLines * 11.5 + 9;
    return { wrappedCells, rowHeight };
  });

  const captionHeight = table.caption ? 14 : 0;
  const firstRowHeight = wrappedRows[0]?.rowHeight ?? 20;
  canvas.ensureSpace(captionHeight + headerHeight + firstRowHeight + 10);

  const drawTableHeader = (): void => {
    const hdrBottomY = canvas.cursorY - headerHeight;
    drawFilledRect(
      canvas.stream,
      MARGIN_X,
      hdrBottomY,
      CONTENT_WIDTH,
      headerHeight,
      theme.bannerRgb,
    );
    for (let c = 0; c < colCount; c++) {
      const cellX = MARGIN_X + c * colWidth;
      const hdrText = table.headers[c] ?? '';
      const clipped =
        hdrText.length > maxCharsPerCell
          ? `${hdrText.slice(0, maxCharsPerCell - 2)}..`
          : hdrText;
      drawText(
        canvas.stream,
        'F2',
        8.5,
        [1.0, 1.0, 1.0],
        cellX + 7,
        hdrBottomY + 7.5,
        clipped,
      );
    }
    canvas.cursorY = hdrBottomY;
  };

  if (table.caption) {
    drawText(
      canvas.stream,
      'F2',
      8.5,
      [0.32, 0.37, 0.45],
      MARGIN_X,
      canvas.cursorY - 9,
      table.caption,
    );
    canvas.cursorY -= 14;
  }

  drawTableHeader();

  wrappedRows.forEach(({ wrappedCells, rowHeight }, rIdx) => {
    if (canvas.cursorY - rowHeight < BOTTOM_SAFE_Y) {
      canvas.pages.push([]);
      canvas.pageIndex += 1;
      canvas.cursorY = TOP_CONTENT_Y_CONT;
      drawTableHeader();
    }

    const rowBottomY = canvas.cursorY - rowHeight;
    const fillRgb: readonly [number, number, number] =
      rIdx % 2 === 1 ? theme.tintRgb : [1.0, 1.0, 1.0];

    drawFilledRect(
      canvas.stream,
      MARGIN_X,
      rowBottomY,
      CONTENT_WIDTH,
      rowHeight,
      fillRgb,
      [0.84, 0.87, 0.91],
      0.45,
    );

    // Subtle internal vertical dividers
    canvas.stream.push('0.86 0.89 0.93 RG');
    canvas.stream.push('0.4 w');
    for (let c = 1; c < colCount; c++) {
      const vx = MARGIN_X + c * colWidth;
      canvas.stream.push(
        `${vx.toFixed(1)} ${rowBottomY.toFixed(1)} m ${vx.toFixed(1)} ${(rowBottomY + rowHeight).toFixed(1)} l S`,
      );
    }

    for (let c = 0; c < colCount; c++) {
      const cellLines = wrappedCells[c] ?? [];
      const cellX = MARGIN_X + c * colWidth + 7;
      let cellY = canvas.cursorY - 12.5;
      for (const cLine of cellLines) {
        drawText(
          canvas.stream,
          c === 0 ? 'F2' : 'F1',
          8.6,
          c === 0 ? [0.1, 0.14, 0.22] : [0.2, 0.24, 0.3],
          cellX,
          cellY,
          cLine,
        );
        cellY -= 11.5;
      }
    }

    canvas.cursorY = rowBottomY;
  });

  canvas.cursorY -= 12;
}

/**
 * Compiles a validated `PdfDocumentSpec` into a publication-grade standards-compliant `%PDF-1.4`
 * binary buffer with executive masthead, metrics, tables, callouts, `/Info` metadata,
 * automatic pagination, running header/footer rendering, and exact `xref` byte offsets.
 */
export function buildPdfBinaryBuffer(rawSpec: PdfDocumentSpec): {
  readonly pdfBytes: Buffer;
  readonly pageCount: number;
  readonly spec: PdfDocumentSpec;
} {
  const spec = validatePdfDocumentSpec(rawSpec);
  const theme = PDF_THEMES[spec.documentType ?? 'technical_report'];
  const canvas = new PdfPageCanvas();

  // 1. Page 1 Masthead
  renderExecutiveMasthead(canvas, spec, theme);

  // 2. Executive Summary Callout (optional)
  if (spec.executiveSummary) {
    renderExecutiveSummaryBox(canvas, spec.executiveSummary, theme);
  }

  // 3. KPI Key Metrics Grid (optional)
  if (spec.keyMetrics && spec.keyMetrics.length > 0) {
    renderKeyMetricsRow(canvas, spec.keyMetrics, theme);
  }

  // 4. Document Sections
  for (let idx = 0; idx < spec.sections.length; idx++) {
    const section = spec.sections[idx]!;
    const numberedHeading = `${idx + 1}. ${section.heading}`;
    const headingLines = wrapTextToLines(numberedHeading, 60);
    const paraLines = wrapTextToLines(section.content, 84);

    // Prevent orphaned section headings: keep heading + at least first 2 paragraph lines together
    const minHeadingBlockHeight =
      10 +
      headingLines.length * 17 +
      8 +
      Math.min(2, paraLines.length) * 14;
    canvas.ensureSpace(minHeadingBlockHeight);

    canvas.cursorY -= idx === 0 ? 2 : 8;

    // Render section heading with accent badge pill/rule
    for (const hLine of headingLines) {
      canvas.cursorY -= 16;
      drawText(
        canvas.stream,
        'F2',
        12.8,
        theme.bannerRgb,
        MARGIN_X,
        canvas.cursorY,
        hLine,
      );
    }

    // Accent underline beneath heading
    canvas.cursorY -= 4;
    canvas.stream.push(rgbStroke(theme.borderRgb));
    canvas.stream.push('0.75 w');
    canvas.stream.push(
      `${MARGIN_X.toFixed(1)} ${canvas.cursorY.toFixed(1)} m ${(MARGIN_X + CONTENT_WIDTH).toFixed(1)} ${canvas.cursorY.toFixed(1)} l S`,
    );
    drawFilledRect(
      canvas.stream,
      MARGIN_X,
      canvas.cursorY - 0.6,
      36,
      1.8,
      theme.accentRgb,
    );
    canvas.cursorY -= 7;

    // Body paragraph
    for (const pLine of paraLines) {
      canvas.ensureSpace(14);
      canvas.cursorY -= 13.5;
      drawText(
        canvas.stream,
        'F1',
        10.0,
        [0.16, 0.18, 0.22],
        MARGIN_X,
        canvas.cursorY,
        pLine,
      );
    }

    canvas.cursorY -= 4;

    // Styled bullet list with crisp accent square markers
    for (const bullet of section.bullets) {
      const wrappedBullet = wrapTextToLines(bullet, 78);
      if (wrappedBullet.length === 0) continue;

      canvas.ensureSpace(wrappedBullet.length * 13 + 3);
      wrappedBullet.forEach((bLine, bIdx) => {
        canvas.cursorY -= 13;
        if (bIdx === 0) {
          drawFilledRect(
            canvas.stream,
            MARGIN_X + 10,
            canvas.cursorY + 2.2,
            3.6,
            3.6,
            theme.accentRgb,
          );
        }
        drawText(
          canvas.stream,
          'F1',
          9.6,
          [0.19, 0.22, 0.27],
          MARGIN_X + 20,
          canvas.cursorY,
          bLine,
        );
      });
      canvas.cursorY -= 2;
    }

    // Optional section callout card
    if (section.callout) {
      canvas.cursorY -= 4;
      renderSectionCallout(canvas, section.callout, theme);
    }

    // Optional structured data table
    if (section.table) {
      canvas.cursorY -= 4;
      renderSectionTable(canvas, section.table, theme);
    }
  }

  const totalPages = canvas.pages.length;

  // Object IDs:
  // 1: Catalog
  // 2: Pages
  // 3: Font F1 (/Helvetica)
  // 4: Font F2 (/Helvetica-Bold)
  // 5: Font F3 (/Helvetica-Oblique)
  // 6: Info metadata dictionary
  // For each page i (0..totalPages-1):
  //   pageObjId = 7 + i * 2
  //   contentObjId = 8 + i * 2
  const objects: string[] = [];
  const pageObjectIds: number[] = [];
  for (let i = 0; i < totalPages; i++) {
    pageObjectIds.push(7 + i * 2);
  }

  objects.push(`1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n`);
  objects.push(
    `2 0 obj\n<< /Type /Pages /Kids [${pageObjectIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${totalPages} >>\nendobj\n`,
  );
  objects.push(
    `3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n`,
  );
  objects.push(
    `4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj\n`,
  );
  objects.push(
    `5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Oblique >>\nendobj\n`,
  );
  objects.push(
    `6 0 obj\n<< /Title (${escapePdfLiteral(spec.title)}) /Subject (${escapePdfLiteral(spec.subtitle)}) /Author (${escapePdfLiteral(spec.author || 'Kartik.ai Editorial Engine')}) /Creator (Kartik.ai PDF Generator) /Producer (Kartik.ai PDF 1.4 Vector Engine) >>\nendobj\n`,
  );

  const shortRunningTitle =
    spec.title.length > 62 ? `${spec.title.slice(0, 59)}...` : spec.title;

  for (let pageIdx = 0; pageIdx < totalPages; pageIdx++) {
    const streamLines = [...canvas.pages[pageIdx]!];
    const pageObjId = 7 + pageIdx * 2;
    const contentObjId = 8 + pageIdx * 2;

    // Running header on continuation pages (Page 2+)
    if (pageIdx > 0) {
      drawFilledRect(
        streamLines,
        MARGIN_X,
        806,
        CONTENT_WIDTH,
        2,
        theme.accentRgb,
      );
      drawText(
        streamLines,
        'F2',
        8.2,
        [0.42, 0.46, 0.54],
        MARGIN_X,
        792,
        shortRunningTitle,
      );
      drawText(
        streamLines,
        'F1',
        8.0,
        theme.accentRgb,
        MARGIN_X + CONTENT_WIDTH - 130,
        792,
        theme.label.slice(0, 26),
      );
      streamLines.push('0.86 0.89 0.93 RG');
      streamLines.push('0.5 w');
      streamLines.push(
        `${MARGIN_X.toFixed(1)} 785.0 m ${(MARGIN_X + CONTENT_WIDTH).toFixed(1)} 785.0 l S`,
      );
    }

    // Footer divider & text ("Generated by Kartik.ai  |  Page X of Y")
    streamLines.push('0.82 0.85 0.90 RG');
    streamLines.push('0.5 w');
    streamLines.push(
      `${MARGIN_X.toFixed(1)} 52.0 m ${(MARGIN_X + CONTENT_WIDTH).toFixed(1)} 52.0 l S`,
    );
    drawText(
      streamLines,
      'F1',
      8.6,
      [0.46, 0.49, 0.55],
      MARGIN_X,
      38,
      `${spec.footer}  |  Page ${pageIdx + 1} of ${totalPages}`,
    );
    if (spec.generatedDate) {
      drawText(
        streamLines,
        'F1',
        8.2,
        [0.54, 0.58, 0.64],
        MARGIN_X + CONTENT_WIDTH - 60,
        38,
        spec.generatedDate,
      );
    }

    const streamContent = streamLines.join('\n') + '\n';
    const streamByteLength = Buffer.byteLength(streamContent, 'ascii');

    objects.push(
      `${pageObjId} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_WIDTH} ${PAGE_HEIGHT}] /Resources << /Font << /F1 3 0 R /F2 4 0 R /F3 5 0 R >> >> /Contents ${contentObjId} 0 R >>\nendobj\n`,
    );
    objects.push(
      `${contentObjId} 0 obj\n<< /Length ${streamByteLength} >>\nstream\n${streamContent}endstream\nendobj\n`,
    );
  }

  let pdfBody = '%PDF-1.4\n';
  const offsets: number[] = [0]; // index 0 is the free object

  for (const objStr of objects) {
    offsets.push(Buffer.byteLength(pdfBody, 'ascii'));
    pdfBody += objStr;
  }

  const xrefOffset = Buffer.byteLength(pdfBody, 'ascii');
  const totalObjCount = objects.length + 1;

  let xref = `xref\n0 ${totalObjCount}\n0000000000 65535 f \n`;
  for (let i = 1; i < offsets.length; i++) {
    const padded = String(offsets[i]!).padStart(10, '0');
    xref += `${padded} 00000 n \n`;
  }

  const trailer = `trailer\n<< /Size ${totalObjCount} /Root 1 0 R /Info 6 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;
  const pdfBytes = Buffer.from(pdfBody + xref + trailer, 'ascii');

  return Object.freeze({
    pdfBytes,
    pageCount: totalPages,
    spec,
  });
}

/**
 * Formats a concise, scannable Markdown summary of the generated PDF document for the assistant message bubble
 * (the full interactive document reader & native PDF viewer renders right below inside `PdfDocumentPreview`).
 */
export function formatPdfSummaryMarkdown(spec: PdfDocumentSpec, pageCount: number): string {
  const tableCount = spec.sections.filter((s) => Boolean(s.table)).length;
  const metricCount = spec.keyMetrics?.length ?? 0;
  const highlights: string[] = [
    `**${pageCount} page${pageCount === 1 ? '' : 's'}**`,
    `**${spec.sections.length} sections**`,
  ];
  if (metricCount > 0) {
    highlights.push(`**${metricCount} KPI metrics**`);
  }
  if (tableCount > 0) {
    highlights.push(`**${tableCount} data table${tableCount === 1 ? '' : 's'}**`);
  }

  const lines: string[] = [
    `Compiled **${spec.title}** (${highlights.join(' · ')}) into a publication-ready \`%PDF-1.4\` binary.`,
  ];

  if (spec.executiveSummary) {
    lines.push('', `> ${spec.executiveSummary}`);
  }

  return lines.join('\n');
}

