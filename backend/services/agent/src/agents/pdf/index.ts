/**
 * Normalizes rich Unicode typography to clean WinAnsi/ASCII equivalents before escaping for PDF literal strings,
 * preventing em-dashes, curly quotes, arrows, and math symbols from being stripped into blank spaces.
 */
export function transliterateForPdf(text: string): string {
  return text
    .replace(/[\u2014\u2015]/g, '--')
    .replace(/[\u2012\u2013\u2212]/g, '-')
    .replace(/[\u2018\u2019\u201A\u2032]/g, "'")
    .replace(/[\u201C\u201D\u201E\u2033]/g, '"')
    .replace(/\u2026/g, '...')
    .replace(/[\u2022\u25CF\u25AA\u25AB]/g, '*')
    .replace(/\u2192/g, '->')
    .replace(/\u2190/g, '<-')
    .replace(/\u2194/g, '<->')
    .replace(/\u2264/g, '<=')
    .replace(/\u2265/g, '>=')
    .replace(/\u00D7/g, 'x')
    .replace(/\u00B1/g, '+/-')
    .replace(/\u00A0/g, ' ')
    .replace(/[\u200B-\u200D\uFEFF]/g, '');
}

/**
 * Escapes characters that have special meaning inside a PDF literal string `(...)`.
 */
function escapePdfLiteral(text: string): string {
  return transliterateForPdf(text)
    .replace(/[^\x20-\x7E]/g, ' ')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

/**
 * Word-wraps a paragraph into lines of at most `maxCharsPerLine` characters, safely splitting overlong tokens.
 */
function wrapTextToLines(text: string, maxCharsPerLine: number): string[] {
  const safeLimit = Math.max(8, Math.floor(maxCharsPerLine));
  const rawWords = transliterateForPdf(text).trim().split(/\s+/).filter(Boolean);
  if (rawWords.length === 0) {
    return [];
  }

  const words: string[] = [];
  for (const w of rawWords) {
    if (w.length <= safeLimit) {
      words.push(w);
    } else {
      for (let i = 0; i < w.length; i += safeLimit) {
        words.push(w.slice(i, i + safeLimit));
      }
    }
  }

  const lines: string[] = [];
  let current = words[0]!;
  for (let i = 1; i < words.length; i++) {
    const word = words[i]!;
    if (current.length + 1 + word.length <= safeLimit) {
      current += ` ${word}`;
    } else {
      lines.push(current);
      current = word;
    }
  }
  lines.push(current);
  return lines;
}

const PAGE_WIDTH = 595.28;
const PAGE_HEIGHT = 841.89;
const MARGIN_X = 48;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN_X * 2; // 499.28 pt
const TOP_CONTENT_Y_FIRST = 794;
const TOP_CONTENT_Y_CONT = 768;
const BOTTOM_SAFE_Y = 70;

function rgbFill(rgb: readonly [number, number, number]): string {
  return `${rgb[0].toFixed(3)} ${rgb[1].toFixed(3)} ${rgb[2].toFixed(3)} rg`;
}

function rgbStroke(rgb: readonly [number, number, number]): string {
  return `${rgb[0].toFixed(3)} ${rgb[1].toFixed(3)} ${rgb[2].toFixed(3)} RG`;
}

function drawText(
  stream: string[],
  font: 'F1' | 'F2' | 'F3',
  size: number,
  colorRgb: readonly [number, number, number],
  x: number,
  y: number,
  text: string,
): void {
  stream.push('BT');
  stream.push(`/${font} ${size.toFixed(1)} Tf`);
  stream.push(rgbFill(colorRgb));
  stream.push(`${x.toFixed(1)} ${y.toFixed(1)} Td`);
  stream.push(`(${escapePdfLiteral(text)}) Tj`);
  stream.push('ET');
}

function drawFilledRect(
  stream: string[],
  x: number,
  y: number,
  w: number,
  h: number,
  fillRgb: readonly [number, number, number],
  strokeRgb?: readonly [number, number, number],
  lineWidth: number = 0.6,
): void {
  stream.push(rgbFill(fillRgb));
  if (strokeRgb) {
    stream.push(rgbStroke(strokeRgb));
    stream.push(`${lineWidth.toFixed(2)} w`);
    stream.push(`${x.toFixed(1)} ${y.toFixed(1)} ${w.toFixed(1)} ${h.toFixed(1)} re B`);
  } else {
    stream.push(`${x.toFixed(1)} ${y.toFixed(1)} ${w.toFixed(1)} ${h.toFixed(1)} re f`);
  }
}

class PdfPageCanvas {
  public readonly pages: string[][] = [[]];
  public pageIndex = 0;
  public cursorY = TOP_CONTENT_Y_FIRST;

  public get stream(): string[] {
    return this.pages[this.pageIndex]!;
  }

  public ensureSpace(neededHeight: number): void {
    if (
      this.cursorY - neededHeight < BOTTOM_SAFE_Y &&
      this.stream.length > 0
    ) {
      this.pages.push([]);
      this.pageIndex += 1;
      this.cursorY = TOP_CONTENT_Y_CONT;
    }
  }
}

function renderExecutiveMasthead(
  canvas: PdfPageCanvas,
  spec: PdfDocumentSpec,
  theme: PdfThemePalette,
): void {
  const titleLines = wrapTextToLines(spec.title, 48);
  const subtitleLines = wrapTextToLines(spec.subtitle, 72);
  const metaParts = [
    spec.generatedDate || new Date().toISOString().slice(0, 10),
    spec.author || 'Kartik.ai Editorial Engine',
    `${spec.sections.length} Section${spec.sections.length === 1 ? '' : 's'}`,
  ];

  const hasRichFrontMatter = Boolean(
    spec.executiveSummary || (spec.keyMetrics && spec.keyMetrics.length > 0),
  );

  // Compact masthead when a minimal spec is supplied (preserves 1-page compact reports),
  // full executive masthead when rich fields are present.
  const padTop = hasRichFrontMatter ? 16 : 12;
  const padBottom = hasRichFrontMatter ? 14 : 10;
  const titleLineHeight = hasRichFrontMatter ? 21 : 19;
  const subtitleLineHeight = 13.5;
  const bannerHeight =
    padTop +
    14 + // category badge
    titleLines.length * titleLineHeight +
    4 +
    subtitleLines.length * subtitleLineHeight +
    16 + // meta strip
    padBottom;

  const bannerBottomY = canvas.cursorY - bannerHeight;
  drawFilledRect(
    canvas.stream,
    MARGIN_X,
    bannerBottomY,
    CONTENT_WIDTH,
    bannerHeight,
    theme.bannerRgb,
  );
  // Crisp left accent stripe inside masthead
  drawFilledRect(
    canvas.stream,
    MARGIN_X,
    bannerBottomY,
    5,
    bannerHeight,
    theme.accentRgb,
  );

  let y = canvas.cursorY - padTop - 8;
  drawText(
    canvas.stream,
    'F2',
    8.0,
    [0.64, 0.82, 0.98],
    MARGIN_X + 18,
    y,
    theme.label,
  );

  y -= 6;
  for (const line of titleLines) {
    y -= titleLineHeight;
    drawText(
      canvas.stream,
      'F2',
      hasRichFrontMatter ? 18.0 : 16.5,
      [1.0, 1.0, 1.0],
      MARGIN_X + 18,
      y,
      line,
    );
  }

  y -= 4;
  for (const line of subtitleLines) {
    y -= subtitleLineHeight;
    drawText(
      canvas.stream,
      'F3',
      10.2,
      [0.82, 0.87, 0.94],
      MARGIN_X + 18,
      y,
      line,
    );
  }

  // Metadata separator + strip
  y -= 8;
  canvas.stream.push('0.25 0.34 0.48 RG');
  canvas.stream.push('0.5 w');
  canvas.stream.push(
    `${(MARGIN_X + 18).toFixed(1)} ${y.toFixed(1)} m ${(MARGIN_X + CONTENT_WIDTH - 16).toFixed(1)} ${y.toFixed(1)} l S`,
  );
  y -= 11;
  drawText(
    canvas.stream,
    'F1',
    8.2,
    [0.72, 0.78, 0.87],
    MARGIN_X + 18,
    y,
    metaParts.join('   |   '),
  );

  canvas.cursorY = bannerBottomY - 14;
}

function renderExecutiveSummaryBox(
  canvas: PdfPageCanvas,
  summary: string,
  theme: PdfThemePalette,
): void {
  const lines = wrapTextToLines(summary, 80);
  if (lines.length === 0) return;

  const lineHeight = 13.5;
  const boxHeight = 24 + lines.length * lineHeight + 10;
  canvas.ensureSpace(boxHeight + 8);

  const boxBottomY = canvas.cursorY - boxHeight;
  drawFilledRect(
    canvas.stream,
    MARGIN_X,
    boxBottomY,
    CONTENT_WIDTH,
    boxHeight,
    theme.tintRgb,
    theme.borderRgb,
    0.7,
  );
  drawFilledRect(
    canvas.stream,
    MARGIN_X,
    boxBottomY,
    4,
    boxHeight,
    theme.accentRgb,
  );

  let y = canvas.cursorY - 16;
  drawText(
    canvas.stream,
    'F2',
    8.5,
    theme.accentRgb,
    MARGIN_X + 14,
    y,
    'EXECUTIVE SUMMARY',
  );
  y -= 4;

  for (const line of lines) {
    y -= lineHeight;
    drawText(
      canvas.stream,
      'F1',
      9.8,
      [0.14, 0.17, 0.23],
      MARGIN_X + 14,
      y,
      line,
    );
  }

  canvas.cursorY = boxBottomY - 12;
}

function renderKeyMetricsRow(
  canvas: PdfPageCanvas,
  metrics: readonly PdfMetricSpec[],
  theme: PdfThemePalette,
): void {
  if (metrics.length === 0) return;
  const count = Math.min(4, metrics.length);
  const gap = 8;
  const cardWidth = (CONTENT_WIDTH - gap * (count - 1)) / count;
  const cardHeight = 52;
  canvas.ensureSpace(cardHeight + 12);

  const boxBottomY = canvas.cursorY - cardHeight;
  for (let i = 0; i < count; i++) {
    const metric = metrics[i]!;
    const cardX = MARGIN_X + i * (cardWidth + gap);
    drawFilledRect(
      canvas.stream,
      cardX,
      boxBottomY,
      cardWidth,
      cardHeight,
      [0.985, 0.99, 0.996],
      theme.borderRgb,
      0.7,
    );
    drawFilledRect(
      canvas.stream,
      cardX,
      boxBottomY + cardHeight - 3,
      cardWidth,
      3,
      theme.accentRgb,
    );

    const maxChars = Math.max(12, Math.floor((cardWidth - 16) / 5.1));
    const labelText =
      metric.label.length > maxChars
        ? `${metric.label.slice(0, maxChars - 2)}..`
        : metric.label;
    const valueText =
      metric.value.length > Math.max(10, Math.floor((cardWidth - 16) / 7.2))
        ? `${metric.value.slice(0, Math.max(8, Math.floor((cardWidth - 16) / 7.2)) - 2)}..`
        : metric.value;

    drawText(
      canvas.stream,
      'F2',
      7.5,
      [0.42, 0.46, 0.54],
      cardX + 9,
      boxBottomY + cardHeight - 14,
      labelText.toUpperCase(),
    );
    drawText(
      canvas.stream,
      'F2',
      13.5,
      theme.bannerRgb,
      cardX + 9,
      boxBottomY + 20,
      valueText,
    );
    if (metric.delta) {
      const deltaText =
        metric.delta.length > maxChars
          ? `${metric.delta.slice(0, maxChars - 2)}..`
          : metric.delta;
      drawText(
        canvas.stream,
        'F1',
        7.8,
        theme.accentRgb,
        cardX + 9,
        boxBottomY + 8,
        deltaText,
      );
    }
  }

  canvas.cursorY = boxBottomY - 14;
}

