import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import {
  buildArtifactRawDownloadUrl,
  parsePptArtifactSlideDeck,
  tokenizeMarkdownBlocks,
} from '../src/index.js';

describe('@kartik/frontend SlideDeckPreview & MarkdownRenderer Tokenizers (9.4.a)', () => {
  it('parses ppt_presentation slides-spec.json into an 8-slide 16:9 interactive deck (Cover + 6 Content + Closing)', () => {
    const rawSpecJson = JSON.stringify({
      slideCount: 8,
      spec: {
        title: 'Zero-Trust Microservices',
        subtitle: 'Ed25519 Signed Context Assertions',
        footer: 'Generated by Kartik.ai',
        slides: Array.from({ length: 6 }, (_, i) => ({
          title: `Slide ${i + 1}: Architecture Layer`,
          subtitle: `Section ${i + 1}`,
          bullets: ['Strict schema isolation', 'Idempotent requestId forwarding'],
        })),
      },
    });

    const deck = parsePptArtifactSlideDeck(rawSpecJson);
    assert.equal(deck.deckTitle, 'Zero-Trust Microservices');
    assert.equal(deck.slides.length, 8);
    assert.equal(deck.slides[0]?.kind, 'cover');
    assert.equal(deck.slides[0]?.slideNumber, 1);
    assert.equal(deck.slides[1]?.kind, 'content');
    assert.equal(deck.slides[1]?.title, 'Slide 1: Architecture Layer');
    assert.equal(deck.slides[7]?.kind, 'closing');
    assert.equal(deck.slides[7]?.slideNumber, 8);
  });

  it('tokenizes Markdown headings, GFM tables, fenced code blocks, blockquotes, and lists accurately', () => {
    const md = [
      '### Architecture Summary',
      '',
      '| Service | Schema |',
      '| :--- | :--- |',
      '| Auth | auth |',
      '| Billing | billing |',
      '',
      '```typescript',
      'const x: number = 42;',
      '```',
      '',
      '- Bullet one',
      '- Bullet two',
    ].join('\n');

    const blocks = tokenizeMarkdownBlocks(md);
    assert.equal(blocks.length, 4);
    assert.equal(blocks[0]?.type, 'heading');
    assert.equal(blocks[1]?.type, 'table');
    if (blocks[1]?.type === 'table') {
      assert.deepEqual(blocks[1].headers, ['Service', 'Schema']);
      assert.equal(blocks[1].rows.length, 2);
    }
    assert.equal(blocks[2]?.type, 'code');
    if (blocks[2]?.type === 'code') {
      assert.equal(blocks[2].language, 'typescript');
      assert.ok(blocks[2].code.includes('const x: number = 42;'));
    }
    assert.equal(blocks[3]?.type, 'list');
    assert.equal(
      buildArtifactRawDownloadUrl('art_ppt_12345'),
      '/api/v1/artifacts/art_ppt_12345/raw',
    );
  });
});
