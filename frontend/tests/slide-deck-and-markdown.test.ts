import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import {
  buildArtifactRawDownloadUrl,
  parsePdfArtifactDocument,
  parsePptArtifactSlideDeck,
  pdfDocumentSpecToMarkdown,
  tokenizeInlineMarkdown,
  tokenizeMarkdownBlocks,
} from '../src/index.js';

describe('@kartik/frontend SlideDeckPreview & MarkdownRenderer Tokenizers (9.4.a)', () => {
  it('parses ppt_presentation slides-spec.json into an 8-slide 16:9 interactive deck (Cover + 6 Content + Closing)', () => {
    const rawSpecJson = JSON.stringify({
      slideCount: 8,
      spec: {
        title: 'Zero-Trust Microservices',
        subtitle: 'Ed25519 Signed Context Assertions',
        footer: 'Generated by Kartik.ai',
        slides: Array.from({ length: 6 }, (_, i) => ({
          title: `Slide ${i + 1}: Architecture Layer`,
          subtitle: `Section ${i + 1}`,
          bullets: ['Strict schema isolation', 'Idempotent requestId forwarding'],
        })),
      },
    });

    const deck = parsePptArtifactSlideDeck(rawSpecJson);
    assert.equal(deck.deckTitle, 'Zero-Trust Microservices');
    assert.equal(deck.slides.length, 8);
    assert.equal(deck.slides[0]?.kind, 'cover');
    assert.equal(deck.slides[0]?.slideNumber, 1);
    assert.equal(deck.slides[1]?.kind, 'content');
    assert.equal(deck.slides[1]?.title, 'Slide 1: Architecture Layer');
    assert.equal(deck.slides[7]?.kind, 'closing');
    assert.equal(deck.slides[7]?.slideNumber, 8);
  });

  it('tokenizes Markdown headings, GFM tables, fenced code blocks, blockquotes, and lists accurately', () => {
    const md = [
      '### Architecture Summary',
      '',
      '| Service | Schema |',
      '| :--- | :--- |',
      '| Auth | auth |',
      '| Billing | billing |',
      '',
      '```typescript',
      'const x: number = 42;',
      '```',
      '',
      '- Bullet one',
      '- Bullet two',
    ].join('\n');

    const blocks = tokenizeMarkdownBlocks(md);
    assert.equal(blocks.length, 4);
    assert.equal(blocks[0]?.type, 'heading');
    assert.equal(blocks[1]?.type, 'table');
    if (blocks[1]?.type === 'table') {
      assert.deepEqual(blocks[1].headers, ['Service', 'Schema']);
      assert.equal(blocks[1].rows.length, 2);
    }
    assert.equal(blocks[2]?.type, 'code');
    if (blocks[2]?.type === 'code') {
      assert.equal(blocks[2].language, 'typescript');
      assert.ok(blocks[2].code.includes('const x: number = 42;'));
    }
    assert.equal(blocks[3]?.type, 'list');
    assert.equal(
      buildArtifactRawDownloadUrl('art_ppt_12345'),
      '/api/v1/artifacts/art_ppt_12345/raw',
    );
  });

  it('Fix #14: tokenizes inline citation markers ([1], [src_2], [1, 3]) and http(s) links while blocking javascript: URLs', () => {
    const tokens = tokenizeInlineMarkdown(
      'PostgreSQL **MVCC** uses `snapshots` [1] and [src_2] plus [1, 3]. See [Docs](https://www.postgresql.org/) or [Bad](javascript:alert(1)).',
    );

    const citationIndices = tokens
      .filter((t) => t.type === 'citation')
      .map((t) => t.index);
    assert.deepEqual(citationIndices, [1, 2, 1, 3]);

    const links = tokens.filter((t) => t.type === 'link');
    assert.equal(links.length, 1);
    assert.equal(links[0]?.label, 'Docs');
    assert.equal(links[0]?.url, 'https://www.postgresql.org/');
  });

  it('Fix #16: parses pdf_document document-spec.json into rich editorial view-model and exports clean Markdown', () => {
    const rawPdfSpecJson = JSON.stringify({
      pageCount: 2,
      documentType: 'proposal',
      spec: {
        title: 'Cloud Security Modernization Proposal',
        subtitle: 'Phased Zero-Trust Architecture Plan',
        documentType: 'proposal',
        author: 'Kartik.ai Editorial Engine',
        generatedDate: '2026-11-20',
        executiveSummary: 'Consolidates identity, rate limits, and audit trails in 12 weeks.',
        keyMetrics: [
          { label: 'Availability', value: '99.95%', delta: 'Multi-AZ' },
          { label: 'ROI', value: '3.2x', delta: 'Year 1' },
        ],
        sections: [
          {
            heading: 'Architecture & Milestones',
            content: 'Phased migration behind strict contract tests.',
            bullets: ['Deploy Ed25519 gateway', 'Enable PostgreSQL RLS'],
            callout: 'All cutovers are guarded by synthetic replay checks.',
            table: {
              caption: 'Table 1: Rollout Plan',
              headers: ['Phase', 'Owner', 'Target'],
              rows: [
                ['Phase 1', 'Platform', 'Week 4'],
                ['Phase 2', 'Security', 'Week 8'],
              ],
            },
          },
        ],
        footer: 'Generated by Kartik.ai',
      },
    });

    const parsed = parsePdfArtifactDocument(rawPdfSpecJson);
    assert.equal(parsed.title, 'Cloud Security Modernization Proposal');
    assert.equal(parsed.documentType, 'proposal');
    assert.equal(parsed.pageCount, 2);
    assert.equal(parsed.keyMetrics.length, 2);
    assert.equal(parsed.sections.length, 1);
    assert.equal(parsed.sections[0]?.table?.headers.length, 3);
    assert.equal(parsed.sections[0]?.table?.rows.length, 2);
    assert.ok(parsed.sections[0]?.callout?.includes('synthetic replay'));

    const markdown = pdfDocumentSpecToMarkdown(parsed);
    assert.ok(markdown.includes('# Cloud Security Modernization Proposal'));
    assert.ok(markdown.includes('## Executive Summary'));
    assert.ok(markdown.includes('| Availability | **99.95%** | Multi-AZ |'));
    assert.ok(markdown.includes('> **Key Takeaway:**'));
    assert.ok(markdown.includes('| Phase | Owner | Target |'));

    // Graceful fallback on malformed/missing manifest JSON
    const fallbackDoc = parsePdfArtifactDocument('{invalid', 'Fallback Report');
    assert.equal(fallbackDoc.title, 'Fallback Report');
    assert.equal(fallbackDoc.sections.length, 1);
  });
});

