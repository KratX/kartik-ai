#!/usr/bin/env python3
"""Generate kartik_ai_build_instructions.md from kartik_ai_blueprint.md.

The blueprint is the single source of truth. The operating instructions live in
the blueprint under a stable heading; this script extracts that block, wraps it
with a provenance header, and writes the standalone file. Never hand-edit the
generated file: edit the blueprint, then run this script.

Usage:
    python3 scripts/sync_instructions.py [blueprint.md] [output.md]

Exit codes:
    0  written
    1  marker not found (blueprint was restructured; fix the markers)
"""

from __future__ import annotations

import hashlib
import sys
from datetime import datetime, timezone
from pathlib import Path

START = "# AI Build-Agent Operating Instructions (mandatory, read before coding)"
END = "# 1. Product definition and completion criteria"

TRAILER = """
## Where to go next

This file is the execution contract only. When a decision is not covered here, the answer is in the blueprint:

| Question | Read |
|---|---|
| What exactly is being built, and what is out of scope? | Section 1 |
| Why are there four services, and who owns what? | Section 2 |
| What does "free tier" actually mean, and which host is the demo on? | Section 3 |
| Where does a file belong in the repository? | Section 4 |
| What are the data shapes, the run-identity rules and the error codes? | Section 5 |
| Which environment variable does this service need? | Section 6 |
| What is the current phase, and what is its exit gate? | Section 7 |
| What tests must exist, and what must never be executed? | Sections 8 and 9 |

**Do not edit this file by hand.** Edit `kartik_ai_blueprint.md`, then run `python3 scripts/sync_instructions.py`.
"""


def main(argv: list[str]) -> int:
    root = Path.cwd()
    if len(argv) > 1:
        src = Path(argv[1])
    elif (root / "kartik_ai_blueprint.md").exists():
        src = root / "kartik_ai_blueprint.md"
    elif (root.parent / "kartik_ai_blueprint.md").exists():
        # Running from inside the repository while the blueprint sits one level up.
        src = root.parent / "kartik_ai_blueprint.md"
    else:
        print("kartik_ai_blueprint.md not found in this directory or its parent", file=sys.stderr)
        return 1
    dst = Path(argv[2]) if len(argv) > 2 else src.with_name("kartik_ai_build_instructions.md")

    text = src.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"marker not found in {src}", file=sys.stderr)
        return 1

    start = text.index(START)
    end = text.index(END)
    block = text[start:end].rstrip()
    # Drop the blueprint's own H1; this file supplies its own title.
    block = block.split("\n", 1)[1].lstrip("\n")
    body = block + "\n"

    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    header = (
        "# Kartik.ai — AI Build-Agent Operating Instructions\n\n"
        "**Generated file. Do not edit by hand.**\n\n"
        "| | |\n|---|---|\n"
        f"| **Source** | `{src.name}` (the single source of truth) |\n"
        "| **Generated by** | `python3 scripts/sync_instructions.py` |\n"
        f"| **Generated on** | {stamp} |\n"
        f"| **Source digest** | `{digest}` (first 16 hex characters of the blueprint SHA-256) |\n"
        "| **Edition** | Matches blueprint v3.0, 9 November 2026 |\n\n"
        "If the digest here does not match the current blueprint, this copy is stale: regenerate it before using it.\n\n"
        "---\n\n"
    )

    dst.write_text(header + body + TRAILER, encoding="utf-8")
    print(f"wrote {dst} ({len((header + body + TRAILER).splitlines())} lines, source digest {digest})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
